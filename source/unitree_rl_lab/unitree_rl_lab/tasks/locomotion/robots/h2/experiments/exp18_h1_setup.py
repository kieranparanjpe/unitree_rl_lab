"""Experiment 18: Unitree's Isaac Lab H1 velocity task (robots/h1/velocity_env_cfg.py, task
Unitree-H1-Velocity) applied to H2, as identically as the two robots allow. Self-contained, not a
baseline subclass. The robot is H2 (UNITREE_H2_CFG); every training setting is H1's.

Mapped to H2, because the names or the geometry differ:
- Feet: H1's ".*ankle.*" is its one foot link per leg; H2 has two ankle links, so the feet are
  ".*ankle_pitch.*" (the foot-bearing link). undesired_contacts keeps "(?!.*ankle.*).*", which on
  H2 leaves out both ankle links.
- joint_deviation_torso: H1's torso_joint is H2's three waist joints.
- joint_deviation_arms: H1's shoulder and elbow joints, as in H1. H2's wrists and head have no
  pose penalty, because H1 has no such joints.
- base_height: H2's own target, 1.0 m (H1's 0.9 m is for H1, which spawns at 1.1 m).

Kept as in H1, although they behave differently from our baseline:
- Turn commands stay within +-0.1 rad/s for the whole run: H1 has only lin_vel_cmd_levels, which
  widens forward and sideways ranges only (upstream as well). ang_vel_z +-0.5 in limit_ranges is
  only the deploy clamp.
- lin_vel_cmd_levels judges only the robots resetting on the check step (see exp5a).
- No zero-snap and no heading mode; commands resampled every 10 s; 2% standing.
- gait_phase and the gait reward are not gated on the command (the clock runs while standing).
- feet_clearance is the +20 bonus (foot_clearance_reward), not the baseline's penalty.
- Episode ends when torso_link touches anything, H2's own arms included.
- No history in the policy or critic observation; critic adds joint efforts.
- Pushes every 5 s, x/y only.
"""

